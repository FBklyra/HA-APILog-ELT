-- 001 roles, warehouse, resource monitor. Run with a role holding CREATE ROLE / CREATE WAREHOUSE.
-- Idempotent: IF NOT EXISTS everywhere. Never touches roles or warehouses of the legacy pipeline (R2).
CREATE ROLE IF NOT EXISTS ALELT_ADMIN;
CREATE ROLE IF NOT EXISTS ALELT_LOADER;
CREATE ROLE IF NOT EXISTS ALELT_READER;
GRANT ROLE ALELT_LOADER TO ROLE ALELT_ADMIN;
GRANT ROLE ALELT_READER TO ROLE ALELT_ADMIN;

CREATE WAREHOUSE IF NOT EXISTS {{WAREHOUSE}}
  WAREHOUSE_SIZE = '{{WAREHOUSE_SIZE}}'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS {{WAREHOUSE}}_RM
  WITH CREDIT_QUOTA = {{CREDIT_QUOTA}}
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND
           ON 110 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE {{WAREHOUSE}} SET RESOURCE_MONITOR = {{WAREHOUSE}}_RM;
GRANT USAGE, OPERATE ON WAREHOUSE {{WAREHOUSE}} TO ROLE ALELT_LOADER;
GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE ALELT_READER;
