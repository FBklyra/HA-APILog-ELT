#include "db2_sql.h"

const char *const db2_sql[Q__COUNT] = {
    /* Q_SCHEMAS */
    "SELECT SCHEMANAME FROM SYSCAT.SCHEMATA WHERE SCHEMANAME NOT LIKE 'SYS%' "
    "AND SCHEMANAME NOT IN ('NULLID', 'SQLJ') ORDER BY SCHEMANAME WITH UR",
    /* Q_TABLES */
    "SELECT TABNAME, TBSPACEID, TABLEID, DATACAPTURE, COMPRESSION, ROWCOMPMODE FROM SYSCAT.TABLES "
    "WHERE TABSCHEMA = ? AND TYPE = 'T' ORDER BY TABNAME WITH UR",
    /* Q_COLUMNS */
    "SELECT C.TABNAME, C.COLNAME, C.COLNO, C.TYPENAME, C.LENGTH, C.SCALE, C.NULLS, C.KEYSEQ, C.CODEPAGE, C.DEFAULT "
    "FROM SYSCAT.COLUMNS C JOIN SYSCAT.TABLES T ON T.TABSCHEMA = C.TABSCHEMA AND T.TABNAME = C.TABNAME "
    "WHERE C.TABSCHEMA = ? AND T.TYPE = 'T' ORDER BY C.TABNAME, C.COLNO WITH UR",
    /* Q_DB_CODEPAGE */
    "SELECT VALUE FROM SYSIBMADM.DBCFG WHERE NAME = 'codepage' WITH UR",
    /* Q_LOG_UTIL */
    "SELECT LOG_UTILIZATION_PERCENT, TOTAL_LOG_USED_KB, TOTAL_LOG_AVAILABLE_KB "
    "FROM SYSIBMADM.MON_TRANSACTION_LOG_UTILIZATION WITH UR",
    /* Q_MON_DB */
    "SELECT LOCK_WAITS, LOCK_TIMEOUTS, DEADLOCKS, NUM_LOCKS_WAITING, TOTAL_CPU_TIME, ROWS_READ, APPLS_CUR_CONS "
    "FROM TABLE(MON_GET_DATABASE(-2)) AS M WITH UR",
    /* Q_LOG_CFG */
    "SELECT NAME, VALUE FROM SYSIBMADM.DBCFG WHERE NAME IN ('logarchmeth1', 'logarchmeth2', 'logfilsiz', "
    "'logprimary', 'logsecond', 'codepage', 'codeset', 'cur_commit') ORDER BY NAME WITH UR",
    /* Q_SNAP_TABLE */
    "SELECT COUNT(*) FROM SYSCAT.TABLES WHERE TABSCHEMA = ? AND TABNAME = ? AND TYPE = 'T' WITH UR",
    /* Q_META_COLS */
    "SELECT COLNAME, KEYSEQ, TYPENAME, CODEPAGE FROM SYSCAT.COLUMNS WHERE TABSCHEMA = ? AND TABNAME = ? "
    "ORDER BY COLNO WITH UR",
    /* Q_UNIQUE_KEYS: key fallback for tables without a primary key = their first unique index by name
     * (same rule as the hub/dev-edge catalog, SRC-db2-07) */
    "SELECT I.TABNAME, I.INDNAME, U.COLNAME, U.COLSEQ FROM SYSCAT.INDEXES I JOIN SYSCAT.INDEXCOLUSE U "
    "ON U.INDSCHEMA = I.INDSCHEMA AND U.INDNAME = I.INDNAME WHERE I.UNIQUERULE = 'U' "
    "AND I.INDEXTYPE IN ('REG', 'CLUS') AND I.TABSCHEMA = ? ORDER BY I.TABNAME, I.INDNAME, U.COLSEQ WITH UR",
    /* Q_PK_TABLES */
    "SELECT DISTINCT TABNAME FROM SYSCAT.COLUMNS WHERE TABSCHEMA = ? AND KEYSEQ > 0 ORDER BY TABNAME WITH UR",
    /* Q_UNIQUE_TAB */
    "SELECT I.INDNAME, U.COLNAME, U.COLSEQ FROM SYSCAT.INDEXES I JOIN SYSCAT.INDEXCOLUSE U "
    "ON U.INDSCHEMA = I.INDSCHEMA AND U.INDNAME = I.INDNAME WHERE I.UNIQUERULE = 'U' "
    "AND I.INDEXTYPE IN ('REG', 'CLUS') AND I.TABSCHEMA = ? AND I.TABNAME = ? ORDER BY I.INDNAME, U.COLSEQ WITH UR",
    /* Q_PARTS: range-partitioned tables - DML log records carry the data partition's object id; the catalog
     * publishes engine_ids["part.<DATAPARTITIONID>"] = TBSPACEID * 65536 + PARTITIONOBJECTID (= alelt_src_db2) */
    "SELECT TABNAME, DATAPARTITIONID, TBSPACEID, PARTITIONOBJECTID FROM SYSCAT.DATAPARTITIONS WHERE TABSCHEMA = ? "
    "ORDER BY TABNAME, DATAPARTITIONID WITH UR",
    /* Q_SERVER_HOST: the server really reached (an alias resolves through the node directory) - deny-list check */
    "SELECT HOST_NAME FROM SYSIBMADM.ENV_SYS_INFO WITH UR",
};
