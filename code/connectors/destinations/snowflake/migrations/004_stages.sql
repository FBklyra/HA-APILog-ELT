-- 004 internal stages. PARQUET holds transient load files; RAW_ARCHIVE keeps raw edge batches (ADR-007).
CREATE STAGE IF NOT EXISTS {{DATABASE}}.ALELT_STAGE.PARQUET
  FILE_FORMAT = (TYPE = PARQUET)
  COMMENT = 'ALELT micro-batch Parquet files (removed after commit)';
CREATE STAGE IF NOT EXISTS {{DATABASE}}.ALELT_STAGE.RAW_ARCHIVE
  COMMENT = 'ALELT raw edge batches, zstd, retention {{RAW_RETENTION_DAYS}} days';
GRANT READ, WRITE ON STAGE {{DATABASE}}.ALELT_STAGE.PARQUET TO ROLE ALELT_LOADER;
GRANT READ, WRITE ON STAGE {{DATABASE}}.ALELT_STAGE.RAW_ARCHIVE TO ROLE ALELT_LOADER;
