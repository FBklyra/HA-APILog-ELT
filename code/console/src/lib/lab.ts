import type { PipelineCreate } from '../api/contract';
import { LAB_CATALOG } from './labCatalog.generated';
import type { LabCatalog, LabProfile } from './labTypes';

/** Compose file and project used by `lab up` (lab/docker-compose.lab.yml). */
export const LAB_COMPOSE_FILE = 'lab/docker-compose.lab.yml';
/** Host name the hub container uses to reach lab ports published on the host. */
export const HUB_HOST = 'host.docker.internal';

/** Keep catalog order, drop unknown ids and duplicates. */
export function orderedSelection(ids: Iterable<string>, catalog: LabCatalog = LAB_CATALOG): string[] {
  const want = new Set(ids);
  return catalog.profiles.filter((p) => want.has(p.id)).map((p) => p.id);
}

export type LabVerb = 'pull' | 'up' | 'down' | 'reset' | 'status';
export interface LabCommands {
  sh: string[];
  ps1: string[];
  compose: string;
}

/** Exact commands for a selection (shown in the zero-risk panel): `lab pull|up|down|reset <ids>` + `lab status`. */
export function labCommands(ids: Iterable<string>, catalog: LabCatalog = LAB_CATALOG,
                            verbs: readonly LabVerb[] = ['pull', 'up', 'status', 'down', 'reset']): LabCommands {
  const sel = orderedSelection(ids, catalog).filter((id) => catalog.profiles.find((p) => p.id === id)?.availability === 'image');
  const args = sel.length ? ' ' + sel.join(' ') : '';
  const lines = (cmd: string) => verbs.map((v) => (v === 'status' ? `${cmd} status` : `${cmd} ${v}${args}`));
  return {
    sh: lines('./lab/lab.sh'),
    ps1: lines('.\\lab\\lab.ps1'),
    compose: `docker compose -p ${catalog.project} -f ${LAB_COMPOSE_FILE} --env-file lab.env up -d`,
  };
}

/** Content of the downloadable `lab.env` (Compose profiles for the selection). */
export function labEnvFile(ids: Iterable<string>, catalog: LabCatalog = LAB_CATALOG, now: Date = new Date()): string {
  const sel = orderedSelection(ids, catalog).filter((id) => catalog.profiles.find((p) => p.id === id)?.availability === 'image');
  return [
    '# ALELT local test lab - generated by the admin console',
    `# ${now.toISOString()} - throw-away containers with fake data only, isolated network "${catalog.network}"`,
    `# Start: docker compose -p ${catalog.project} -f ${LAB_COMPOSE_FILE} --env-file lab.env up -d`,
    `# Stop:  docker compose -p ${catalog.project} -f ${LAB_COMPOSE_FILE} --env-file lab.env down`,
    `COMPOSE_PROJECT_NAME=${catalog.project}`,
    `COMPOSE_PROFILES=${sel.join(',')}`,
    '',
  ].join('\n');
}

/** Connection fields as `key=value` lines (passwords included: lab-only throw-away values). */
export function connectionLines(p: LabProfile): string[] {
  return Object.entries(p.connection ?? {}).map(([k, v]) => `${k}=${String(v)}`);
}

export const sources = (c: LabCatalog = LAB_CATALOG) => c.profiles.filter((p) => p.kind === 'source');
export const targets = (c: LabCatalog = LAB_CATALOG) => c.profiles.filter((p) => p.kind === 'target');
/** amd64-only images run under emulation on ARM64 hosts (native on x64). */
export const amd64Only = (p: LabProfile) => p.availability === 'image' && (p.images?.length ?? 0) > 0 && !(p.arch ?? []).includes('arm64');

/** Settings for `POST /wizard/destination/test` from the guidance form: drop empty values and `<placeholder>` values. */
export function guidanceSettings(values: Record<string, string>): Record<string, string | number> {
  const out: Record<string, string | number> = {};
  for (const [k, v] of Object.entries(values)) {
    const x = v.trim();
    if (!x || x.includes('<')) continue;
    out[k] = /^\d+$/.test(x) && k === 'port' ? Number(x) : x;
  }
  return out;
}

/**
 * Body for `POST /wizard/pipelines` that creates a TEST demo pipeline from a lab source into the lab landing
 * Postgres. Hosts are rewritten to `host.docker.internal` because the hub runs in a container.
 */
export function demoPipelineBody(source: LabProfile, landing: LabProfile, reason = 'local lab demo'): PipelineCreate {
  const { password, ...rest } = source.connection ?? {};
  const src: Record<string, unknown> = { ...rest, host: HUB_HOST };
  const l = landing.connection ?? {};
  const url = `postgresql://${String(l.user)}:${encodeURIComponent(String(l.password))}@${HUB_HOST}:${String(l.port)}/${String(l.database)}`;
  return {
    reason,
    connection_id: `lab_${source.id}`,
    environment: 'TEST',
    source_engine: source.demo?.source_engine ?? source.engine,
    source: src,
    ...(password !== undefined ? { password: { value: String(password) } } : {}),
    destination_engine: 'postgres',
    destination: { url, schema: `lab_${source.id}` },
  };
}

/** Helper link parameters from the URL fragment `#helper=<url>&token=<t>`. */
export function parseHelperFragment(hash: string): { url: string; token: string } | null {
  const q = new URLSearchParams(hash.replace(/^#/, ''));
  const url = q.get('helper');
  const token = q.get('token');
  if (!url || !token) return null;
  if (!isLoopbackUrl(url)) return null;
  return { url: url.replace(/\/+$/, ''), token };
}

/** The helper is only ever accepted on the local machine (127.0.0.1 / localhost / [::1]). */
export function isLoopbackUrl(u: string): boolean {
  try {
    const x = new URL(u);
    return (x.protocol === 'http:' || x.protocol === 'https:') && ['127.0.0.1', 'localhost', '[::1]'].includes(x.hostname);
  } catch {
    return false;
  }
}
