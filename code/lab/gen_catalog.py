"""Generate lab/catalog.json and console/src/lib/labCatalog.generated.ts from lab/catalog.yaml.

  python lab/gen_catalog.py           # write both files
  python lab/gen_catalog.py --check   # exit 1 if they are out of date (used by tests / CI)

catalog.yaml is the single source of truth. catalog.json exists so the lab scripts and the helper need no YAML
library (PowerShell ConvertFrom-Json, Python json). The TS file is imported by the console's Local test lab screen.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SRC = HERE / "catalog.yaml"
OUT_JSON = HERE / "catalog.json"
OUT_TS = REPO / "console" / "src" / "lib" / "labCatalog.generated.ts"

REQUIRED = {"id", "kind", "engine", "label", "availability", "status"}


def load() -> dict:
    import yaml  # dev-time dependency only (PyYAML)

    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    ids = set()
    for p in data["profiles"]:
        missing = REQUIRED - p.keys()
        if missing:
            raise SystemExit(f"profile {p.get('id')}: missing {sorted(missing)}")
        if p["id"] in ids:
            raise SystemExit(f"duplicate profile id {p['id']}")
        ids.add(p["id"])
        if p["kind"] not in ("source", "target") or p["availability"] not in ("image", "no_image"):
            raise SystemExit(f"profile {p['id']}: bad kind/availability")
        if p["status"] not in ("stable", "beta", "planned"):
            raise SystemExit(f"profile {p['id']}: bad status")
        if p["availability"] == "image":
            for k in ("images", "arch", "services", "ports"):
                p.setdefault(k, [] if k != "ports" else {})
        elif "guidance" not in p:
            raise SystemExit(f"profile {p['id']}: no_image entries need guidance")
    return data


def render(data: dict) -> tuple[str, str]:
    js = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    ts = ("// GENERATED by lab/gen_catalog.py from lab/catalog.yaml - do not edit by hand.\n"
          "// SPDX-License-Identifier: Apache-2.0\n"
          "import type { LabCatalog } from './labTypes';\n\n"
          f"export const LAB_CATALOG: LabCatalog = {json.dumps(data, indent=2, ensure_ascii=False)};\n")
    return js, ts


def main() -> int:
    js, ts = render(load())
    if "--check" in sys.argv:
        stale = [str(p.relative_to(REPO)) for p, body in ((OUT_JSON, js), (OUT_TS, ts))
                 if not p.is_file() or p.read_text(encoding="utf-8") != body]
        if stale:
            print("out of date (run python lab/gen_catalog.py):", ", ".join(stale))
            return 1
        return 0
    OUT_JSON.write_text(js, encoding="utf-8", newline="\n")
    OUT_TS.write_text(ts, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_JSON.relative_to(REPO)} and {OUT_TS.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
