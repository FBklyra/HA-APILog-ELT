-- ALELT Oracle LogMiner test setup (DEDICATED dev container alelt-test-oracle ONLY), run as SYSDBA in CDB$ROOT.
-- These are the DBA steps the prerequisite fix-it SQL shows for a real source.
SHUTDOWN IMMEDIATE;
STARTUP MOUNT;
ALTER DATABASE ARCHIVELOG;
ALTER DATABASE OPEN;
ALTER PLUGGABLE DATABASE ALL OPEN;
ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;
ALTER SESSION SET CONTAINER = FREEPDB1;
-- test schema owner + capture user (per-PDB LogMiner, Oracle 21c+)
DECLARE n NUMBER; BEGIN
  SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME = 'ALELTTEST';
  IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE USER ALELTTEST IDENTIFIED BY alelttest QUOTA UNLIMITED ON USERS'; END IF;
  SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME = 'ALELT_CAPTURE';
  IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE USER ALELT_CAPTURE IDENTIFIED BY aleltcapture'; END IF;
END;
/
GRANT CREATE SESSION, CREATE TABLE TO ALELTTEST;
GRANT CREATE SESSION, LOGMINING, SELECT ANY TRANSACTION, SELECT_CATALOG_ROLE, SELECT ANY TABLE, FLASHBACK ANY TABLE TO ALELT_CAPTURE;
GRANT EXECUTE ON SYS.DBMS_LOGMNR TO ALELT_CAPTURE;
EXIT;
