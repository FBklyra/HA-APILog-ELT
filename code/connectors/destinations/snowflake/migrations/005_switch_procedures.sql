-- 005 view switch procedures (ADR-006). Views use the explicit column list in ALELT_CONTROL.VIEW_COLUMNS (never a star select).
-- SOURCE = 'ALELT' (landing schema) requires a valid certification; 'LEGACY' (existing landing schema of the
-- legacy pipeline) is the rollback. The procedure owner needs SELECT on the legacy schema; that grant is made by the
-- account admin, not here (R2).
CREATE OR REPLACE PROCEDURE {{DATABASE}}.ALELT_CONTROL.SWITCH_SOURCE(TABLE_NAME VARCHAR, SOURCE VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  bad_input EXCEPTION (-20001, 'SWITCH_SOURCE: invalid table name or source');
  not_certified EXCEPTION (-20002, 'SWITCH_SOURCE: table has no valid certification');
  no_columns EXCEPTION (-20003, 'SWITCH_SOURCE: no registered view columns');
  no_legacy EXCEPTION (-20004, 'SWITCH_SOURCE: no legacy schema configured');
  src_schema VARCHAR;
  prev_source VARCHAR;
  col_list VARCHAR;
  certified INTEGER;
  ddl VARCHAR;
BEGIN
  IF (NOT REGEXP_LIKE(:TABLE_NAME, '^[A-Za-z0-9_$]+$') OR :SOURCE NOT IN ('LEGACY', 'ALELT')) THEN
    RAISE bad_input;
  END IF;
  IF (:SOURCE = 'ALELT') THEN
    SELECT COUNT(*) INTO :certified FROM {{DATABASE}}.ALELT_CONTROL.CERTIFICATION
     WHERE TABLE_NAME = :TABLE_NAME AND CERTIFIED
       AND (VALID_UNTIL IS NULL OR VALID_UNTIL > CURRENT_TIMESTAMP());
    IF (:certified = 0) THEN
      INSERT INTO {{DATABASE}}.ALELT_CONTROL.SWITCH_AUDIT (TABLE_NAME, TO_SOURCE, OUTCOME, MESSAGE)
        VALUES (:TABLE_NAME, :SOURCE, 'REFUSED', 'not certified');
      RAISE not_certified;
    END IF;
    src_schema := '{{LANDING_SCHEMA}}';
  ELSE
    src_schema := '{{LEGACY_SCHEMA}}';
    IF (:src_schema = '') THEN
      RAISE no_legacy;
    END IF;
  END IF;
  SELECT LISTAGG('"' || COLUMN_NAME || '"', ', ') WITHIN GROUP (ORDER BY ORDINAL) INTO :col_list
    FROM {{DATABASE}}.ALELT_CONTROL.VIEW_COLUMNS WHERE TABLE_NAME = :TABLE_NAME;
  IF (:col_list IS NULL OR :col_list = '') THEN
    RAISE no_columns;
  END IF;
  SELECT MAX(ACTIVE_SOURCE) INTO :prev_source FROM {{DATABASE}}.ALELT_CONTROL.SWITCH_STATE WHERE TABLE_NAME = :TABLE_NAME;
  ddl := 'CREATE OR REPLACE VIEW {{DATABASE}}.{{VIEW_SCHEMA}}."' || :TABLE_NAME || '" COPY GRANTS AS SELECT '
         || :col_list || ' FROM {{DATABASE}}.' || :src_schema || '."' || :TABLE_NAME || '"';
  EXECUTE IMMEDIATE :ddl;
  MERGE INTO {{DATABASE}}.ALELT_CONTROL.SWITCH_STATE t
    USING (SELECT :TABLE_NAME AS TABLE_NAME) s ON t.TABLE_NAME = s.TABLE_NAME
    WHEN MATCHED THEN UPDATE SET ACTIVE_SOURCE = :SOURCE, SWITCHED_AT = CURRENT_TIMESTAMP(), SWITCHED_BY = CURRENT_USER()
    WHEN NOT MATCHED THEN INSERT (TABLE_NAME, ACTIVE_SOURCE, SWITCHED_AT, SWITCHED_BY)
      VALUES (s.TABLE_NAME, :SOURCE, CURRENT_TIMESTAMP(), CURRENT_USER());
  INSERT INTO {{DATABASE}}.ALELT_CONTROL.SWITCH_AUDIT (TABLE_NAME, FROM_SOURCE, TO_SOURCE, OUTCOME)
    VALUES (:TABLE_NAME, :prev_source, :SOURCE, 'OK');
  RETURN :TABLE_NAME || ' -> ' || :SOURCE;
END;
$$;

CREATE OR REPLACE PROCEDURE {{DATABASE}}.ALELT_CONTROL.SWITCH_WAVE(WAVE_ID VARCHAR, SOURCE VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  not_certified EXCEPTION (-20012, 'SWITCH_WAVE: at least one table in the wave is not certified');
  missing INTEGER DEFAULT 0;
  n INTEGER DEFAULT 0;
  tname VARCHAR;
  c1 CURSOR FOR SELECT TABLE_NAME FROM {{DATABASE}}.ALELT_CONTROL.WAVE WHERE WAVE_ID = ? ORDER BY TABLE_NAME;
BEGIN
  IF (:SOURCE = 'ALELT') THEN
    SELECT COUNT(*) INTO :missing FROM {{DATABASE}}.ALELT_CONTROL.WAVE w
      LEFT JOIN {{DATABASE}}.ALELT_CONTROL.CERTIFICATION c
        ON c.TABLE_NAME = w.TABLE_NAME AND c.CERTIFIED
       AND (c.VALID_UNTIL IS NULL OR c.VALID_UNTIL > CURRENT_TIMESTAMP())
     WHERE w.WAVE_ID = :WAVE_ID AND c.TABLE_NAME IS NULL;
    IF (:missing > 0) THEN
      RAISE not_certified;
    END IF;
  END IF;
  OPEN c1 USING (:WAVE_ID);
  FOR rec IN c1 DO
    tname := rec.TABLE_NAME;
    CALL {{DATABASE}}.ALELT_CONTROL.SWITCH_SOURCE(:tname, :SOURCE);
    UPDATE {{DATABASE}}.ALELT_CONTROL.SWITCH_AUDIT SET WAVE_ID = :WAVE_ID
     WHERE TABLE_NAME = :tname AND WAVE_ID IS NULL AND AT >= DATEADD(minute, -5, CURRENT_TIMESTAMP());
    n := n + 1;
  END FOR;
  CLOSE c1;
  RETURN :WAVE_ID || ': ' || :n || ' table(s) -> ' || :SOURCE;
END;
$$;

CREATE OR REPLACE PROCEDURE {{DATABASE}}.ALELT_CONTROL.SWITCH_WAVE(WAVE_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  res VARCHAR;
BEGIN
  CALL {{DATABASE}}.ALELT_CONTROL.SWITCH_WAVE(:WAVE_ID, 'ALELT') INTO :res;
  RETURN :res;
END;
$$;

