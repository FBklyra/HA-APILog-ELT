CREATE TABLE IF NOT EXISTS {{DATABASE}}.ALELT_CONTROL.AUDIT_BATCH (
  BATCH_ID      VARCHAR(64)   NOT NULL,
  STREAM        VARCHAR(200)  NOT NULL,
  TABLE_NAME    VARCHAR(400),
  FROM_POS      VARCHAR(400),
  TO_POS        VARCHAR(400)  NOT NULL,
