-- 002 schemas: landing, control, stage, view interface.
CREATE DATABASE IF NOT EXISTS {{DATABASE}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{LANDING_SCHEMA}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.ALELT_CONTROL;
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.ALELT_STAGE;
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{VIEW_SCHEMA}};

GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE ALELT_LOADER;
GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE ALELT_READER;
GRANT USAGE, CREATE TABLE ON SCHEMA {{DATABASE}}.{{LANDING_SCHEMA}} TO ROLE ALELT_LOADER;
GRANT USAGE ON SCHEMA {{DATABASE}}.ALELT_CONTROL TO ROLE ALELT_LOADER;
GRANT USAGE, CREATE TABLE ON SCHEMA {{DATABASE}}.ALELT_STAGE TO ROLE ALELT_LOADER;
GRANT USAGE, CREATE VIEW ON SCHEMA {{DATABASE}}.{{VIEW_SCHEMA}} TO ROLE ALELT_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA {{DATABASE}}.{{LANDING_SCHEMA}} TO ROLE ALELT_LOADER;

-- dbt and other consumers read the view interface only (master spec §8).
GRANT USAGE ON SCHEMA {{DATABASE}}.{{VIEW_SCHEMA}} TO ROLE ALELT_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA {{DATABASE}}.{{VIEW_SCHEMA}} TO ROLE ALELT_READER;
